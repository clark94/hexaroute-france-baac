USE DATABASE HEXAROUTE_DB;
USE SCHEMA ANALYTICS;

CREATE OR REPLACE VIEW KPI_NATIONAUX AS
SELECT ANNEE, COUNT(*) AS ACCIDENTS,
       COUNT_IF(ACCIDENT_MORTEL) AS ACCIDENTS_MORTELS,
       SUM(NB_TUES) AS PERSONNES_TUEES,
       SUM(NB_BLESSES_GRAVES) AS BLESSES_HOSPITALISES,
       SUM(NB_VEHICULES) AS VEHICULES_IMPLIQUES
FROM ACCIDENTS GROUP BY ANNEE;

CREATE OR REPLACE VIEW KPI_MENSUELS AS
SELECT ANNEE, DATE_TRUNC('MONTH', DATE) AS MOIS,
       COUNT(*) AS ACCIDENTS, SUM(NB_TUES) AS PERSONNES_TUEES
FROM ACCIDENTS WHERE DATE IS NOT NULL
GROUP BY ANNEE, DATE_TRUNC('MONTH', DATE);

CREATE OR REPLACE VIEW KPI_DEPARTEMENTS AS
SELECT ANNEE, DEPARTEMENT, COUNT(*) AS ACCIDENTS,
       SUM(NB_TUES) AS PERSONNES_TUEES,
       SUM(NB_VEHICULES) AS VEHICULES_IMPLIQUES
FROM ACCIDENTS GROUP BY ANNEE, DEPARTEMENT;
