USE DATABASE HEXAROUTE_DB;
USE SCHEMA ANALYTICS;

-- Au plus une ligne par année et accident. Cette requête doit retourner 0 ligne.
SELECT ANNEE, NUM_ACC, COUNT(*) AS N
FROM ACCIDENTS GROUP BY ANNEE, NUM_ACC HAVING COUNT(*) > 1;

-- Contrôle des volumes et des victimes.
SELECT ANNEE, COUNT(*) AS ACCIDENTS, SUM(NB_USAGERS) AS USAGERS,
       SUM(NB_VEHICULES) AS VEHICULES,
       SUM(NB_TUES) AS PERSONNES_TUEES
FROM ACCIDENTS GROUP BY ANNEE ORDER BY ANNEE;

SELECT * FROM KPI_NATIONAUX ORDER BY ANNEE;
SELECT * FROM KPI_MENSUELS ORDER BY ANNEE, MOIS;
SELECT * FROM KPI_DEPARTEMENTS ORDER BY ANNEE, ACCIDENTS DESC;
