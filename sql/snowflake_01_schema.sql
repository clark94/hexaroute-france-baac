-- HexaRoute | schéma Snowflake, exécutable dans Workspaces.
-- Sélectionner un rôle autorisé à créer une base; conserver le warehouse existant.
CREATE DATABASE IF NOT EXISTS HEXAROUTE_DB;
USE DATABASE HEXAROUTE_DB;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;
USE SCHEMA ANALYTICS;

CREATE TABLE IF NOT EXISTS ACCIDENTS (
  ANNEE INTEGER, NUM_ACC VARCHAR(40), DEPARTEMENT VARCHAR(6), COMMUNE_CODE VARCHAR(16),
  DATE DATE, MOIS_NUM INTEGER, JOUR_SEMAINE INTEGER, HEURE INTEGER,
  LATITUDE FLOAT, LONGITUDE FLOAT, LUM INTEGER, ATM INTEGER, AGG INTEGER,
  MILIEU VARCHAR(60), LUMINOSITE VARCHAR(70), METEO VARCHAR(70),
  VMA FLOAT, CATEGORIE_ROUTE VARCHAR(20), NB_VEHICULES INTEGER,
  NB_USAGERS INTEGER, NB_TUES INTEGER, NB_BLESSES_GRAVES INTEGER,
  NB_BLESSES_LEGERS INTEGER, ACCIDENT_MORTEL BOOLEAN, GRAVITE_ACCIDENT VARCHAR(65)
);
CREATE TABLE IF NOT EXISTS USAGERS (
  ANNEE INTEGER, NUM_ACC VARCHAR(40), GRAVITE_CODE INTEGER,
  SEXE VARCHAR(25), PROFIL VARCHAR(35), AGE FLOAT
);
